-- ===== etablissements_etape1c_coherence
-- une ligne rattachée à une faculté appartient forcément à l'établissement de cette faculté
create or replace function public.set_establishment_from_faculty() returns trigger
language plpgsql security definer set search_path='' as $$
begin
  if new.faculty_id is not null then
    new.establishment_id := (select f.establishment_id from public.faculties f where f.id=new.faculty_id);
  end if;
  if new.establishment_id is null then new.establishment_id := public.current_establishment(); end if;
  return new;
end $$;
do $$ declare t text; begin
  foreach t in array array['user_roles','calendar_closures','announcements','profiles'] loop
    execute format('create trigger %I before insert or update of faculty_id, establishment_id on public.%I for each row execute function public.set_establishment_from_faculty()', t||'_fac_etab', t);
  end loop;
end $$;
