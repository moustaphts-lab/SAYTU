create or replace function public.set_establishment_from_parent() returns trigger
language plpgsql security definer set search_path='' as $$
begin
  if tg_table_name='departments' then
    new.establishment_id := (select f.establishment_id from public.faculties f where f.id=new.faculty_id);
  elsif tg_table_name='programs' then
    new.establishment_id := (select d.establishment_id from public.departments d where d.id=new.department_id);
  elsif tg_table_name='courses' then
    new.establishment_id := (select d.establishment_id from public.departments d where d.id=new.department_id);
  elsif tg_table_name='student_groups' then
    new.establishment_id := (select p.establishment_id from public.programs p where p.id=new.program_id);
  elsif tg_table_name='teachers' then
    new.establishment_id := coalesce((select d.establishment_id from public.departments d where d.id=new.department_id),
                                     new.establishment_id, public.current_establishment());
  elsif tg_table_name='payslips' then
    new.establishment_id := (select f.establishment_id from public.pay_periods pp join public.faculties f on f.id=pp.faculty_id where pp.id=new.pay_period_id);
  end if;
  if new.establishment_id is null then raise exception 'Établissement introuvable.'; end if;
  return new;
end $$;

do $$ declare t text; begin
