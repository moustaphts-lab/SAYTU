-- établissement de la personne connectée ; tant qu'il n'existe qu'un établissement, c'est celui-là
create or replace function public.current_establishment() returns bigint
language sql stable security definer set search_path='' as $$
  select coalesce(
    (select p.establishment_id from public.profiles p where p.id=auth.uid()),
    (select e.id from public.establishments e where (select count(*) from public.establishments)=1)
  ) $$;

